TAG_NAME = re.compile(r'TagName="([^"]*)"')
NUMBER = r"-?(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][+-]?\d+)?"
STRING = r'"(?:[^"\\]|\\.)*"'


class Refusal(Exception):
    pass


def read_bytes(root, rel):
    path = os.path.join(root, rel)
    if not os.path.isfile(path):
        raise Refusal("%s: not found under %s" % (rel, root))
    with open(path, "rb") as f:
        return f.read()


def decode(rel, data):
    if data.startswith(b"\xef\xbb\xbf"):
        raise Refusal("%s: starts with a BOM - the Tools/data files and the tests have none; look before running" % rel)
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError as e:
        raise Refusal("%s: not UTF-8 (%s)" % (rel, e))


def is_number(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def same(found, want):
    if is_number(want):
        return is_number(found) and float(found) == float(want)
    return found == want


def show(v):
    return json.dumps(v, ensure_ascii=False)


def plan_rules(root, notes):
    """Returns (new text or None, [change lines])."""
    data = read_bytes(root, RULES)
    text = decode(RULES, data)
    try:
        rows = json.loads(text)
    except ValueError as e:
        raise Refusal("%s: not valid JSON (%s)" % (RULES, e))
    named = [r for r in rows if isinstance(r, dict) and r.get("Name") == "rules"] if isinstance(rows, list) else []
    if len(named) != 1:
        raise Refusal("%s: expected exactly one row named \"rules\", found %d" % (RULES, len(named)))
    row = named[0]
    for old in OLD_KNOB_NAMES:
        if old in row:
            raise Refusal("%s: the row still spells the old knob %s - this tree has not had decision 3's rename "
                          "([B-7x1] - rename_leaves.py); run that first" % (RULES, old))
    missing = [k for k, _, _, _ in KNOBS if k not in row]
    if missing:
        raise Refusal("%s: the row \"rules\" lacks %s - the knobs come with [B-7x1]; this tree is not ready for [B-7x5s]"
                      % (RULES, ", ".join(missing)))

    changes = []
    edits = []   # (start, end, new literal)
    for key, inert, target, literal in KNOBS:
        found = row[key]
        hits = [m for m in re.finditer(r'"%s"\s*:\s*' % re.escape(key), text)]
        if len(hits) != 1:
            raise Refusal("%s: the key %s is written %d times in the text; expected once" % (RULES, key, len(hits)))
        start = hits[0].end()
        m = re.compile(NUMBER if is_number(target) else STRING).match(text, start)
        if not m or json.loads(m.group(0)) != found or (is_number(found) != is_number(target)):
            raise Refusal("%s: cannot read the value of %s in place (found %r in the parsed row) - look before running"
                          % (RULES, key, found))
        after = text[m.end():m.end() + 1]
        if after not in (",", "\n", "\r", " ", "\t", "}"):
            raise Refusal("%s: unexpected text after the value of %s - look before running" % (RULES, key))
        spelled = m.group(0)
        if same(found, target):
            if spelled != literal:
                notes.append("  %s: already %s (spelled %s, aa09543 spells %s - left as is)" % (key, show(target), spelled, literal))
            else:
                notes.append("  %s: already %s" % (key, spelled))
            continue
        if key == "BrickSeedTags" and found == tags_text(SEEDS_OLD_SPELLING):
            changes.append("  %s: the target in aa09543's old leaf spelling -> new spelling (Brick.Diet.SilenceFeed -> Brick.Diet.IdleFeed)\n"
                           "      %s\n   -> %s" % (key, spelled, literal))
            edits.append((m.start(), m.end(), literal))
            continue
        if not same(found, inert):
            raise Refusal("%s: %s is %s - neither the inert default %s nor the target %s. Someone set it in between "
                          "(a [B-7x5r] retune, a B6b change, a hand edit?): decide by hand, then run again"
                          % (RULES, key, spelled, show(inert), literal))
        changes.append("  %s: %s -> %s" % (key, spelled, literal))
        edits.append((m.start(), m.end(), literal))

    if not edits:
        return None, changes
    new = text
    for s, e, lit in sorted(edits, reverse=True):
        new = new[:s] + lit + new[e:]
    # Proof of the edit: the parsed rows equal the old ones with the targets put in, nothing else moved.
    want = json.loads(text)
    for r in want:
        if isinstance(r, dict) and r.get("Name") == "rules":
            for key, _, target, _ in KNOBS:
                if not same(r[key], target):
                    r[key] = target
    got = json.loads(new)
    if json.dumps(got, sort_keys=False) != json.dumps(want, sort_keys=False) or list(got[0].keys()) != list(json.loads(text)[0].keys()):
        raise Refusal("%s: internal check failed - the edited text does not parse to the intended rows" % RULES)
    if new.count("\n") != text.count("\n") or new.count("\r") != text.count("\r"):
        raise Refusal("%s: internal check failed - the line count or line ends changed" % RULES)
    return new, changes


def plan_tests(root, notes):
    text = decode(TESTS, read_bytes(root, TESTS))
    # The file's own line ends (LF in the repository; a checkout or an archive with core.autocrlf may give CRLF).
    eol = "\r\n" if "\r\n" in text else "\n"
    old_block, new_block = TEST_OLD.replace("\n", eol), TEST_NEW.replace("\n", eol)
    n_old, n_new = text.count(old_block), text.count(new_block)
    if n_new == 1 and n_old == 0:
        notes.append("  %s: the start-value pin is already in test_existence_vocabulary" % TESTS)
        return None, []
    if n_old == 1 and n_new == 0:
        new = text.replace(old_block, new_block)
        lines = ["  %s: test_existence_vocabulary - the inert pin of the knobs becomes the start-value pin:" % TESTS]
        lines += ["    - " + l for l in TEST_OLD.rstrip("\n").split("\n")]
        lines += ["    + " + l for l in TEST_NEW.rstrip("\n").split("\n")]
        return new, lines
    raise Refusal("%s: expected the inert pin of [B-7x2] once (found %d) or the start pin once (found %d) in "
                  "test_existence_vocabulary - the block was rewritten since the integration branch; port aa09543's "
                  "swap by hand (start values as in this script's TEST_NEW)" % (TESTS, n_old, n_new))


def check_schema(root, notes):
    text = decode(SCHEMA, read_bytes(root, SCHEMA))
    schema = json.loads(text)
    table = schema.get("tables", {}).get("DT_Rules", {})
    columns = table.get("columns", {})
    problems = [k for k, _, _, _ in KNOBS if k not in columns]
    seed = columns.get("BrickSeedTags", {})
    if seed and (seed.get("kind") != "tags" or seed.get("root") != "Brick."):
        problems.append("BrickSeedTags is not {kind: tags, root: Brick.} (header 3.3 rule 6)")
    gt0 = set()
    for rule in table.get("rules", []):
        for then in rule.get("then", []):
            if then.get("gt") == 0:
                gt0.add(then.get("col"))
    problems += ["no above-0 rule for %s (header 3.3 rule 6)" % c for c in SCHEMA_GT0 if c not in gt0]
    if problems:
        raise Refusal("%s: the [B-7x1] schema lines this commit relies on are missing: %s" % (SCHEMA, "; ".join(problems)))
    # The target values against the column bounds, so a refusal comes here and not from check_data later.
    for key, _, target, _ in KNOBS:
        spec = columns[key]
        if is_number(target):
            if "min" in spec and target < spec["min"] or "max" in spec and target > spec["max"] \
                    or spec.get("integer") and float(target) != int(target):
                raise Refusal("%s: the target %s of %s breaks its column %s" % (SCHEMA, target, key, show(spec)))
    notes.append("  %s: nothing to add - aa09543 adds no knob line (its schema lines are [B-7x5c]'s); the knob columns, "
                 "the above-0 rule and the seed tags' root Brick. are there" % SCHEMA)


def check_ini(root):
    text = decode(INI, read_bytes(root, INI))
    declared = set(re.findall(r'^\+GameplayTagList=\(Tag="([^"]+)"', text, re.M))
    missing = [s for s in SEEDS if s not in declared]
    if missing:
        raise Refusal("%s: the seed bricks %s are not declared - the tree lacks [B-7x1]'s tags in the new leaf names"
                      % (INI, ", ".join(missing)))
    assert not SETTLE_BARRING & set(SEEDS)


def regen_docs(root, dry_run, rules_change):
    """Returns (docs/30 written?, [lines])."""
    tool = os.path.join(root, CONFIG_REF)
    if not os.path.isfile(tool):
        return False, ["  %s: no %s in the tree - regenerate docs/30 by hand" % (DOCS30, CONFIG_REF)] if rules_change else []
    if dry_run:
        if rules_change:
            return False, ["  %s: would be regenerated by %s after the knob values are written" % (DOCS30, CONFIG_REF)]
        check = subprocess.run([sys.executable, "-I", tool, "--check"], cwd=root, capture_output=True, text=True, encoding="utf-8")
        return False, [] if check.returncode == 0 else ["  %s: stale - would be regenerated by %s" % (DOCS30, CONFIG_REF)]
    check = subprocess.run([sys.executable, "-I", tool, "--check"], cwd=root, capture_output=True, text=True, encoding="utf-8")
    if check.returncode == 0:
        return False, []
    path = os.path.join(root, DOCS30)
    before = open(path, encoding="utf-8").read().split("\n") if os.path.isfile(path) else []
    run = subprocess.run([sys.executable, "-I", tool], cwd=root, capture_output=True, text=True, encoding="utf-8")
    if run.returncode != 0:
        return False, ["  %s: %s failed (exit %d): %s" % (DOCS30, CONFIG_REF, run.returncode, (run.stderr or run.stdout).strip())]
    after = open(path, encoding="utf-8").read().split("\n")
    lines = ["  %s: regenerated by %s:" % (DOCS30, CONFIG_REF)]
    gone = [l for l in before if l not in set(after)]
    came = [l for l in after if l not in set(before)]
    lines += ["    - " + l for l in gone] + ["    + " + l for l in came]
    if not gone and not came:
        lines.append("    (line order only)")
    return True, lines


def main(argv):
    args = [a for a in argv if not a.startswith("--")]
    flags = [a for a in argv if a.startswith("--")]
    if len(args) != 1 or any(f != "--dry-run" for f in flags):
        print(__doc__.split("\n\n")[1])
        return 2
    root = os.path.abspath(args[0])
    dry_run = "--dry-run" in flags
    print("[B-7x5s] port of aa09543's DT_Rules share into %s%s" % (root, " (dry run - nothing is written)" if dry_run else ""))
    notes = []
    try:
        check_ini(root)
        check_schema(root, notes)
        rules_new, rules_changes = plan_rules(root, notes)
        tests_new, tests_changes = plan_tests(root, notes)
    except Refusal as e:
        print("REFUSED - nothing was written:\n  " + str(e))
        return 1

    writes = [(RULES, rules_new), (TESTS, tests_new)]
    changes = rules_changes + tests_changes
    if notes:
        print("Unchanged:")
        print("\n".join(notes))
    if changes:
        print("Changes%s:" % (" that would be made" if dry_run else ""))
        print("\n".join(changes))
    if not dry_run:
        for rel, new in writes:
            if new is not None:
                with open(os.path.join(root, rel), "wb") as f:
                    f.write(new.encode("utf-8"))
    docs_written, docs = regen_docs(root, dry_run, rules_new is not None)
    if docs:
        print("\n".join(docs))
    edited = [rel for rel, new in writes if new is not None] + ([DOCS30] if docs_written else [])
    if not edited and not docs:
        print("Nothing to change: the tree already holds the [B-7x5s] share (0 changes).")
        return 0
    knobs = sum(1 for c in rules_changes if c.startswith("  Brick"))
    if dry_run:
        print("Would change %d knob value(s) in %s; would write %s." % (
            knobs, RULES, ", ".join([rel for rel, new in writes if new is not None] + ([DOCS30] if docs else []))))
    else:
        print("Changed %d knob value(s) in %s; wrote %s." % (knobs, RULES, ", ".join(edited) if edited else "nothing"))
    print("Follow-ups (never done here):\n"
          "  - python -I -X utf8 <rename_leaves.py> %s  (its second run must report 0: the seeds are already in the new names),\n"
          "    and the old-leaf grep of notes 5.4 code-7 over Source/ Config/ Tools/\n"
          "  - python -I Tools/check_data.py and python -I Tools/test_data_schema.py\n"
          "  - editor closed: powershell -ExecutionPolicy Bypass -File Tools\\run_checks.ps1 -Tier full -Data  (twice; DT_Rules.json\n"
          "    is in the stamp generated.sha1 - Data.SourcesInSync fails until the assets are made again)\n"
          "  - the [B-7x5s] proofs of header section 8 row 6 (the world moves - AI only)" % root)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
